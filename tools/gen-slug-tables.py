# Generates ui/slug_tables.h, the tables ui/slug.c needs to reproduce
# python-slugify (what the upstream UI uses to name rules):
#
#   - unidecode: code point -> ASCII transliteration, for the ranges below;
#   - nfkd: code point -> unicodedata.normalize('NFKD', c).lower(), with
#     every non-ASCII character of the result replaced by \x7f (it ends up
#     as a separator anyway), for the same ranges plus the code points of
#     the HTML entities;
#   - entities: html.entities.name2codepoint.
#
# Needs python3 with the `unidecode` module (python3-unidecode), the one
# python-slugify picks. Run it again when moving to a new upstream if
# slugify changed, and commit the result.
import html.entities
import sys
import unicodedata

import unidecode

RANGES = [
    (0x0080, 0x036F),  # Latin-1 Supplement, Latin Extended-A/B, IPA,
                       # spacing modifiers, combining marks
    (0x0370, 0x04FF),  # Greek, Cyrillic
    (0x1E00, 0x1EFF),  # Latin Extended Additional
    (0x2000, 0x218F),  # General Punctuation, super/subscripts, currency,
                       # letterlike symbols, number forms
    (0xFB00, 0xFB4F),  # Alphabetic Presentation Forms (ligatures)
    (0xFF00, 0xFFEF),  # Halfwidth and Fullwidth Forms
]


def c_string(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\':
            out.append('\\' + ch)
        elif 0x20 <= o < 0x7f:
            out.append(ch)
        else:
            out.append('\\%03o' % o)
    return '"' + ''.join(out) + '"'


def nfkd_lower(cp):
    s = unicodedata.normalize('NFKD', chr(cp)).lower()
    return ''.join(c if ord(c) < 0x80 else '\x7f' for c in s)


def main():
    cps = []
    for lo, hi in RANGES:
        cps.extend(range(lo, hi + 1))
    nfkd_cps = sorted(set(cps) | set(html.entities.name2codepoint.values()))

    out = sys.stdout
    out.write('/* Generated by tools/gen-slug-tables.py (unidecode %s, Unicode %s):\n'
              ' * do not edit. */\n' % (getattr(unidecode, '__version__', '?'),
                                        unicodedata.unidata_version))
    out.write('#ifndef KS_UI_SLUG_TABLES_H\n#define KS_UI_SLUG_TABLES_H\n\n')
    out.write('#include <stdint.h>\n\n')
    out.write('struct ks_slug_cp { uint32_t cp; const char *s; };\n')
    out.write('struct ks_slug_entity { const char *name; uint32_t cp; };\n\n')

    out.write('static const struct ks_slug_cp ks_slug_unidecode[] = {\n')
    for cp in cps:
        out.write('    {0x%04X, %s},\n' % (cp, c_string(unidecode.unidecode(chr(cp)))))
    out.write('};\n\n')

    out.write('static const struct ks_slug_cp ks_slug_nfkd[] = {\n')
    for cp in nfkd_cps:
        out.write('    {0x%04X, %s},\n' % (cp, c_string(nfkd_lower(cp))))
    out.write('};\n\n')

    out.write('/* Sorted by name (strcmp). */\n')
    out.write('static const struct ks_slug_entity ks_slug_entities[] = {\n')
    for name in sorted(html.entities.name2codepoint, key=lambda n: n.encode()):
        out.write('    {"%s", 0x%04X},\n' % (name, html.entities.name2codepoint[name]))
    out.write('};\n\n#endif\n')


if __name__ == '__main__':
    main()
